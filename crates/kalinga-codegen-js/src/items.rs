//! Top-level items: enums, structs, classes, functions, constants and `main`.

use std::fmt::Write as _;

use kalinga_sema::tast::TBody;
use kalinga_sema::{Bound, Signature, Type};
use kalinga_syntax::ast::Program;

use crate::{Gen, RUNTIME, fn_id, indent, jid, js_str, method_id, type_id};

impl Gen<'_> {
    pub(crate) fn program(&self, prog: &Program) -> String {
        let mut out = String::from("// Generated by the Kalinga compiler.\n\"use strict\";\n");
        out.push_str(RUNTIME);
        for x in prog.extern_fns.iter().filter(|x| self.reach.externs.contains(&x.name)) {
            if let Some(js) = &x.js {
                let names: Vec<&str> = x.params.iter().map(|p| p.name.as_str()).collect();
                let _ = writeln!(
                    out,
                    "\n// extern fn {} (inline JavaScript)\nfunction x${}({}) {{{}}}",
                    x.name,
                    x.name,
                    names.join(", "),
                    js
                );
            } else if x.body.is_some() {
                let _ = writeln!(
                    out,
                    "\nfunction x${}() {{\n  return $kl.unsupported({});\n}}",
                    x.name,
                    js_str(&format!("the inline Rust function `{}`", x.name))
                );
            }
        }
        for ename in &self.m.enum_order {
            self.enum_show(&mut out, ename);
        }
        for name in self.m.struct_order.iter().filter(|n| self.reach.types.contains(*n)) {
            self.struct_decl(&mut out, name);
        }
        let mut classes: Vec<&String> = self.m.class_order.iter().filter(|n| self.reach.types.contains(*n)).collect();
        // Base classes first: `class B extends A` needs `A` to exist.
        classes.sort_by_key(|c| self.m.ancestors(c).len());
        for cname in classes {
            self.class(&mut out, cname);
        }
        for f in &prog.functions {
            let Some(b) = self.t.functions.get(&f.name) else { continue };
            if !self.reach.functions.contains(&f.name) {
                continue;
            }
            if f.name == "main" && !self.tests {
                self.main_decl(&mut out, b);
                continue;
            }
            let _ = writeln!(out, "\nfunction {}({}) {{\n{}}}", fn_id(&f.name), params(&b.sig), self.body(b, 1));
        }
        self.statics(&mut out, prog);
        if self.tests {
            self.test_runner(&mut out);
        } else {
            self.main_call(&mut out);
        }
        out
    }

    /// The statements of a function or method body. The early return of `value?` is caught
    /// here, and an `async fn` gives back a job that runs the body when awaited.
    fn body(&self, b: &TBody, depth: usize) -> String {
        self.body_as(b, depth, b.is_async, b.is_async)
    }

    /// A body written as async code (`await` allowed) and/or wrapped in a lazy job.
    fn body_as(&self, b: &TBody, depth: usize, is_async: bool, lazy: bool) -> String {
        self.shared.borrow_mut().clear();
        let was_async = self.in_async.replace(is_async);
        let inner = if lazy { depth + 1 } else { depth };
        let mut stmts = self.block_inner(&b.stmts, inner);
        self.in_async.set(was_async);
        if stmts.contains("$kl.try") {
            stmts = format!(
                "{i}try {{
{}{i}}} catch ($e) {{
{i}  if ($e instanceof $kl.Ret) return $e.v;
{i}  throw $e;
{i}}}
",
                reindent(&stmts),
                i = indent(inner)
            );
        }
        if lazy {
            format!(
                "{i}return $kl.lazy(async () => {{
{}{i}}});
",
                stmts,
                i = indent(depth)
            )
        } else {
            stmts
        }
    }

    /// `main`: an async function when it waits for async code with `Async.run`.
    fn main_decl(&self, out: &mut String, b: &TBody) {
        self.block_on.set(true);
        self.used_block_on.set(false);
        let mut body = self.body(b, 1);
        let mut head = "function";
        if self.used_block_on.get() && !b.is_async {
            body = self.body_as(b, 1, true, false);
            head = "async function";
        }
        self.block_on.set(false);
        let _ = writeln!(
            out,
            "
{} {}({}) {{
{}}}",
            head,
            fn_id("main"),
            params(&b.sig),
            body
        );
    }

    fn main_call(&self, out: &mut String) {
        let on_result = match self.m.functions.get("main").map(|s| &s.ret) {
            Some(Type::Result(_, e)) => format!(", $kl.mainResult({})", self.shower(e)),
            _ => String::new(),
        };
        let _ = writeln!(out, "\n$init_statics();\n$kl.main({}{});", fn_id("main"), on_result);
    }

    /// The analysed file's `test fn`s, run one after another with fresh `static var`s.
    fn test_runner(&self, out: &mut String) {
        let mut list = vec![];
        for (i, t) in self.t.tests.iter().filter(|t| t.pos.file == 0).enumerate() {
            let _ = writeln!(out, "\n// test fn {}\nfunction t${}() {{\n{}}}", t.name, i, self.body(&t.body, 1));
            list.push(format!("[{}, t${}]", js_str(&t.name), i));
        }
        let _ = writeln!(out, "\n$kl.tests([{}], $init_statics);", list.join(", "));
    }

    /// `show$Name(v)` for every enum: `Circle(2.0)`, `Empty`.
    fn enum_show(&self, out: &mut String, name: &str) {
        let info = &self.m.enums[name];
        let _ = writeln!(out, "\nfunction show${}(v) {{", name);
        for (v, fields) in &info.variants {
            if fields.is_empty() {
                continue;
            }
            let shows: Vec<String> =
                fields.iter().enumerate().map(|(i, (_, t))| self.show(&format!("v.f[{}]", i), t)).collect();
            let _ = writeln!(
                out,
                "  if (v.t === {}) return {} + {} + \")\";",
                js_str(v),
                js_str(&format!("{}(", v)),
                shows.join(" + \", \" + ")
            );
        }
        out.push_str("  return v.t;\n}\n");
    }

    /// Top-level `const`s and `const` members as functions computing the value (a fresh
    /// copy each time); `static var` members as module variables set by `$init_statics`.
    fn statics(&self, out: &mut String, prog: &Program) {
        for c in prog.consts.iter().filter(|c| self.reach.consts.contains(&c.name)) {
            let Some(v) = self.t.static_values.get(&(String::new(), c.name.clone())) else { continue };
            let _ = writeln!(out, "\nfunction k${}() {{\n  return {};\n}}", c.name, self.expr(v));
        }
        let mut init = String::new();
        for owner in self.m.struct_order.iter().chain(&self.m.class_order) {
            for (name, s) in self.m.static_values_of(owner).unwrap_or_default() {
                if !self.reach.statics.contains(&(owner.clone(), name.clone())) {
                    continue;
                }
                let Some(v) = self.t.static_values.get(&(owner.clone(), name.clone())) else { continue };
                if s.mutable {
                    let _ = writeln!(out, "let s${}${};", owner, name);
                    let _ = writeln!(init, "  s${}${} = {};", owner, name, self.expr(v));
                } else {
                    let _ = writeln!(out, "\nfunction c${}${}() {{\n  return {};\n}}", owner, name, self.expr(v));
                }
            }
        }
        let _ = writeln!(out, "\nfunction $init_statics() {{\n{}}}", init);
    }

    /// A struct: a class with its fields, copies, printing, comparison, methods and
    /// operators.
    fn struct_decl(&self, out: &mut String, name: &str) {
        let info = &self.m.structs[name];
        let fields: Vec<&String> = info.fields.iter().map(|(f, _)| f).collect();
        let names: Vec<String> = fields.iter().map(|f| jid(f)).collect();
        let _ = writeln!(out, "\nclass {} {{", type_id(name));
        let _ = writeln!(out, "  constructor({}) {{", names.join(", "));
        for (f, n) in fields.iter().zip(&names) {
            let _ = writeln!(out, "    this.{} = {};", f, n);
        }
        out.push_str("  }\n");
        let copies: Vec<String> = fields.iter().map(|f| format!("$kl.clone(this.{})", f)).collect();
        let _ = writeln!(out, "  __clone() {{\n    return new {}({});\n  }}", type_id(name), copies.join(", "));
        if self.m.struct_has(name, &Bound::Show) {
            out.push_str("  __show() {\n    return this.$as_str();\n  }\n");
        } else {
            let _ = writeln!(out, "  __show() {{\n    return {};\n  }}", self.fields_show(name, &info.fields));
        }
        if self.m.struct_writes(name, &Bound::Eq) {
            out.push_str("  __eq(o) {\n    return this.$equals($kl.clone(o));\n  }\n");
        } else {
            let _ = writeln!(out, "  __eq(o) {{\n    return {};\n  }}", fields_eq(&info.fields, "o"));
        }
        if self.m.struct_has(name, &Bound::Ord) {
            out.push_str("  __cmp(o) {\n    return Math.sign(this.$compare($kl.clone(o)));\n  }\n");
        }
        for meth in &info.decl.methods {
            let (Some(m), Some(b)) =
                (info.methods.get(&meth.name), self.t.struct_methods.get(&(name.to_string(), meth.name.clone())))
            else {
                continue;
            };
            let stat = if m.is_static { "static " } else { "" };
            let _ =
                writeln!(out, "  {}{}({}) {{\n{}  }}", stat, method_id(&meth.name), params(&m.sig), self.body(b, 2));
        }
        let mut generated: Vec<&String> = info.generated.iter().collect();
        generated.sort();
        for g in generated {
            let body = match g.as_str() {
                "as_str" => self.fields_show(name, &info.fields),
                "equals" => fields_eq(&info.fields, "other"),
                _ => fields_cmp(&info.fields, "other"),
            };
            let other = if g == "as_str" { "" } else { "other" };
            let _ = writeln!(out, "  {}({}) {{\n    return {};\n  }}", method_id(g), other, body);
        }
        for o in &info.ops {
            let Some(b) = self.t.struct_ops.get(&(name.to_string(), o.index)) else { continue };
            let _ = writeln!(out, "  op${}({}) {{\n{}  }}", o.index, params(&b.sig), self.body(b, 2));
        }
        out.push_str("}\n");
    }

    /// `"Name(a: 1, b: 2)"` built from `this`'s fields.
    fn fields_show(&self, name: &str, fields: &[(String, Type)]) -> String {
        if fields.is_empty() {
            return js_str(&format!("{}()", name));
        }
        let mut parts = vec![];
        for (i, (f, t)) in fields.iter().enumerate() {
            let label = if i == 0 { format!("{}({}: ", name, f) } else { format!(", {}: ", f) };
            parts.push(js_str(&label));
            parts.push(self.show(&format!("this.{}", f), t));
        }
        parts.push("\")\"".into());
        parts.join(" + ")
    }

    fn class(&self, out: &mut String, cname: &str) {
        let info = &self.m.classes[cname];
        let ext = info.parent.as_ref().map_or(String::new(), |p| format!(" extends {}", type_id(p)));
        let _ = writeln!(out, "\nclass {}{} {{", type_id(cname), ext);
        // Construction: fields get their defaults (base classes first), then `init` runs.
        let ctor = self.m.find_init(cname);
        let ctor_params = ctor.as_ref().map(|(_, s)| params(s)).unwrap_or_default();
        let _ = writeln!(
            out,
            "  static $new({}) {{\n    const o = new {}();\n    o.__defaults();",
            ctor_params,
            type_id(cname)
        );
        if let Some((owner, _)) = &ctor {
            let _ = writeln!(out, "    o.__init_{}({});", owner, ctor_params);
        }
        out.push_str("    return o;\n  }\n");
        out.push_str("  __defaults() {\n");
        if info.parent.is_some() {
            out.push_str("    super.__defaults();\n");
        }
        for (f, t) in &info.fields {
            let value = match self.t.field_defaults.get(&(cname.to_string(), f.clone())) {
                Some(e) => self.expr(e),
                None => default_value(t),
            };
            let _ = writeln!(out, "    this.{} = {};", f, value);
        }
        out.push_str("  }\n");
        if let (Some(sig), Some(b)) = (&info.init, self.t.inits.get(cname)) {
            let _ = writeln!(out, "  __init_{}({}) {{\n{}  }}", cname, params(sig), self.body(b, 2));
        }
        for meth in &info.decl.methods {
            let key = (cname.to_string(), meth.name.clone());
            if let Some(b) = self.t.statics.get(&key).filter(|_| info.statics.contains_key(&meth.name)) {
                let _ =
                    writeln!(out, "  static {}({}) {{\n{}  }}", method_id(&meth.name), params(&b.sig), self.body(b, 2));
            } else if let Some(Some(b)) = self.t.methods.get(&key) {
                let _ = writeln!(out, "  {}({}) {{\n{}  }}", method_id(&meth.name), params(&b.sig), self.body(b, 2));
            }
        }
        let mut generated: Vec<&String> = info.generated.iter().collect();
        generated.sort();
        for g in generated {
            let _ = writeln!(out, "  {}{}", method_id(g), self.class_generated(cname, g));
        }
        if self.m.class_has(cname, &Bound::Show) {
            out.push_str("  __show() {\n    return this.$as_str();\n  }\n");
        }
        if self.m.class_has(cname, &Bound::Eq) {
            out.push_str("  __eq(o) {\n    return this === o || this.$equals(o);\n  }\n");
        }
        if self.m.class_has(cname, &Bound::Ord) {
            out.push_str("  __cmp(o) {\n    return this === o ? 0 : Math.sign(this.$compare(o));\n  }\n");
        }
        out.push_str("}\n");
        // Interface default methods the class does not define.
        for iname in self.m.all_interfaces(cname) {
            for (mname, sig) in &self.m.interfaces[&iname].methods {
                if self.m.find_method(cname, mname).is_some() {
                    continue;
                }
                let Some(b) = self.t.iface_methods.get(&(iname.clone(), mname.clone())) else { continue };
                let _ = writeln!(
                    out,
                    "{}.prototype.{} = function ({}) {{\n{}}};",
                    type_id(cname),
                    method_id(mname),
                    params(sig),
                    self.body(b, 1)
                );
            }
        }
    }

    /// `(params) { body }` of a method the compiler writes for a class listing `Show`, `Eq`
    /// or `Ord`, from the fields (base class fields first).
    fn class_generated(&self, owner: &str, method: &str) -> String {
        let fields: Vec<(String, Type)> = self.m.all_fields(owner).into_iter().map(|(f, t, _)| (f, t)).collect();
        match method {
            "as_str" => format!("() {{\n    return {};\n  }}", self.fields_show(owner, &fields)),
            "equals" => format!(
                "(other) {{\n    if (this === other) return true;\n    return {};\n  }}",
                fields_eq(&self.root_fields(owner, method), "other")
            ),
            _ => format!(
                "(other) {{\n    if (this === other) return 0;\n    return {};\n  }}",
                fields_cmp(&self.root_fields(owner, method), "other")
            ),
        }
    }

    /// The fields of the class `other` has in a generated `equals` / `compare`.
    fn root_fields(&self, owner: &str, method: &str) -> Vec<(String, Type)> {
        let root = match self.m.classes[owner].methods.get(method).and_then(|s| s.params.first()) {
            Some((_, Type::Class(root))) => root.clone(),
            _ => owner.to_string(),
        };
        self.m.all_fields(&root).into_iter().map(|(f, t, _)| (f, t)).collect()
    }
}

/// Parameter names of a signature.
fn params(sig: &Signature) -> String {
    sig.params.iter().map(|(n, _)| jid(n)).collect::<Vec<_>>().join(", ")
}

/// `this.a === o.a && $kl.eq(this.b, o.b)`.
fn fields_eq(fields: &[(String, Type)], other: &str) -> String {
    if fields.is_empty() {
        return "true".into();
    }
    fields
        .iter()
        .map(|(f, t)| match t {
            Type::Int | Type::Float | Type::Bool | Type::Str => format!("this.{f} === {other}.{f}"),
            _ => format!("$kl.eq(this.{f}, {other}.{f})"),
        })
        .collect::<Vec<_>>()
        .join(" && ")
}

/// The first non-zero `$kl.cmp` of the fields, in order.
fn fields_cmp(fields: &[(String, Type)], other: &str) -> String {
    if fields.is_empty() {
        return "0".into();
    }
    fields.iter().map(|(f, _)| format!("$kl.cmp(this.{f}, {other}.{f})")).collect::<Vec<_>>().join(" || ")
}

/// The value a field starts with when it declares no default.
fn default_value(t: &Type) -> String {
    match t {
        Type::Int | Type::Float => "0".into(),
        Type::Bool => "false".into(),
        Type::Str => "\"\"".into(),
        Type::Array(_) => "[]".into(),
        Type::Map(..) => "$kl.map([])".into(),
        // A generic class's `T` field has no value until it is set.
        Type::Param(_) => "undefined".into(),
        _ => "null".into(),
    }
}

/// Statements indented one level more.
fn reindent(stmts: &str) -> String {
    stmts.lines().map(|l| if l.is_empty() { "\n".to_string() } else { format!("  {}\n", l) }).collect()
}
